package entities

import (
	"time"

	"github.com/jackc/pgx/v5/pgtype"
)

type ObligationStatus string

const (
	ObligationStatusPending ObligationStatus = "PENDING"
	ObligationStatusPaid    ObligationStatus = "PAID"
)

type Obligation struct {
	ID                  pgtype.UUID      `db:"id"`
	UserID              pgtype.UUID      `db:"user_id"`
	Name                string           `db:"name"`
	Amount              int64            `db:"amount"`
	DueDate             pgtype.Date      `db:"due_date"`
	Status              ObligationStatus `db:"status"`
	Frequency           *string          `db:"frequency"`
	PaidAt              *time.Time       `db:"paid_at"`
	PaidTransactionID   pgtype.UUID      `db:"paid_transaction_id"`
	PaidTransactionType TransactionType  `db:"paid_transaction_type"` // Generated by PostgreSQL.
	Timestamps
}
