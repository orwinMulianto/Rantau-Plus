package entities

import "github.com/jackc/pgx/v5/pgtype"

type Category struct {
	ID             pgtype.UUID     `db:"id"`
	UserID         pgtype.UUID     `db:"user_id"` // NULL for shared categories.
	Name           string          `db:"name"`
	Type           TransactionType `db:"type"`
	OwnershipScope string          `db:"ownership_scope"` // Generated by PostgreSQL.
	Timestamps
}
