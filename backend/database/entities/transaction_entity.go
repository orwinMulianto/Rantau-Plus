package entities

import "github.com/jackc/pgx/v5/pgtype"

type Transaction struct {
	ID                     pgtype.UUID     `gorm:"type:uuid;primaryKey;default:gen_random_uuid();uniqueIndex:transactions_user_id_id_key,priority:2"`
	UserID                 pgtype.UUID     `gorm:"type:uuid;not null;uniqueIndex:transactions_user_id_id_key,priority:1;index:transactions_period_date_idx,priority:1"`
	PeriodID               pgtype.UUID     `gorm:"type:uuid;not null;index:transactions_period_date_idx,priority:2"`
	CategoryID             pgtype.UUID     `gorm:"type:uuid;not null"`
	Type                   TransactionType `gorm:"type:text;not null;check:transactions_type_check,type IN ('INCOME', 'EXPENSE')"`
	Amount                 int64           `gorm:"type:bigint;not null;check:transactions_amount_check,amount > 0"`
	TransactionDate        pgtype.Date     `gorm:"type:date;not null;index:transactions_period_date_idx,priority:3"`
	Note                   *string         `gorm:"type:text"`
	CategoryIsShared       bool            `gorm:"not null;default:true;-:migration"`
	CategoryOwnershipScope string          `gorm:"type:text;-:migration;->"` // Generated by PostgreSQL.
	Timestamps
}
