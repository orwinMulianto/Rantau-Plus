package entities

import "github.com/jackc/pgx/v5/pgtype"

type Transaction struct {
	ID                     pgtype.UUID     `db:"id"`
	UserID                 pgtype.UUID     `db:"user_id"`
	PeriodID               pgtype.UUID     `db:"period_id"`
	CategoryID             pgtype.UUID     `db:"category_id"`
	Type                   TransactionType `db:"type"`
	Amount                 int64           `db:"amount"`
	TransactionDate        pgtype.Date     `db:"transaction_date"`
	Note                   *string         `db:"note"`
	CategoryIsShared       bool            `db:"category_is_shared"`
	CategoryOwnershipScope string          `db:"category_ownership_scope"` // Generated by PostgreSQL.
	Timestamps
}
