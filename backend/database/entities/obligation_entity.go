package entities

import (
	"time"

	"github.com/jackc/pgx/v5/pgtype"
)

type ObligationStatus string

const (
	ObligationStatusPending ObligationStatus = "PENDING"
	ObligationStatusPaid    ObligationStatus = "PAID"
)

type Obligation struct {
	ID                  pgtype.UUID      `gorm:"type:uuid;primaryKey;default:gen_random_uuid()"`
	UserID              pgtype.UUID      `gorm:"type:uuid;not null;index:obligations_pending_due_idx,priority:1,where:status = 'PENDING'"`
	SetupPeriodID       pgtype.UUID      `gorm:"type:uuid;-:migration"`
	Name                string           `gorm:"type:text;not null"`
	Amount              int64            `gorm:"type:bigint;not null;check:obligations_amount_check,amount > 0"`
	DueDate             pgtype.Date      `gorm:"type:date;not null;index:obligations_pending_due_idx,priority:2"`
	Status              ObligationStatus `gorm:"type:text;not null;default:PENDING;check:obligations_status_check,status IN ('PENDING', 'PAID')"`
	Frequency           *string          `gorm:"type:text"`
	PaidAt              *time.Time       `gorm:"type:timestamptz"`
	PaidTransactionID   pgtype.UUID      `gorm:"type:uuid;uniqueIndex:obligations_paid_transaction_id_key;check:obligations_check,(status = 'PENDING' AND paid_at IS NULL AND paid_transaction_id IS NULL) OR (status = 'PAID' AND paid_at IS NOT NULL AND paid_transaction_id IS NOT NULL)"`
	PaidTransactionType TransactionType  `gorm:"type:text;-:migration;->"` // Generated by PostgreSQL.
	Timestamps
}
